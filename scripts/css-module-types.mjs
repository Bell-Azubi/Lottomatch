/**
 * Generates typed declarations (`x.module.d.css.ts`) for every CSS module under src/, so a
 * misspelled class name fails the typecheck. `--check` verifies they are up to date (CI).
 */
import { glob, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');

/** Extracts class selectors, ignoring comments, strings and url() values. */
export function classNames(css) {
  const stripped = css
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/url\([^)]*\)/g, '')
    .replace(/'[^']*'|"[^"]*"/g, '');
  const names = new Set();
  for (const match of stripped.matchAll(/\.(-?[_a-zA-Z][\w-]*)/g)) names.add(match[1]);
  return [...names].sort();
}

function declaration(names) {
  const body = names.map((name) => `  readonly ${name}: string;`).join('\n');
  return `// Generated by scripts/css-module-types.mjs. Do not edit.\ndeclare const styles: {\n${body}\n};\nexport default styles;\n`;
}

let stale = 0;
for await (const file of glob('src/**/*.module.css', { cwd: root })) {
  const path = join(root, file);
  const names = classNames(await readFile(path, 'utf8'));
  const invalid = names.filter((name) => !/^[a-z][a-zA-Z0-9]*$/.test(name));
  if (invalid.length > 0) {
    console.error(`${file}: use camelCase class names (${invalid.join(', ')})`);
    process.exitCode = 1;
    continue;
  }
  const target = path.replace(/\.module\.css$/, '.module.d.css.ts');
  const expected = declaration(names);
  const current = await readFile(target, 'utf8').catch(() => '');
  if (current === expected) continue;
  if (check) {
    console.error(`${file}: typed declaration is out of date (run npm run css-types)`);
    stale += 1;
  } else {
    await writeFile(target, expected);
  }
}
if (stale > 0) process.exitCode = 1;
